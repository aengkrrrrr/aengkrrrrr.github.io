// ============================================================
//  MBTI 4축 점수 → 결과 매핑 함수
// ============================================================
function calcResult(scores) {
  // 각 축의 우세 유형 결정
  const E_I = scores.E >= scores.I ? "E" : "I";
  const N_S = scores.N >= scores.S ? "N" : "S";
  const F_T = scores.F >= scores.T ? "F" : "T";
  const P_J = scores.P >= scores.J ? "P" : "J";
  const mbtiType = E_I + N_S + F_T + P_J;

  // MBTI 유형 → 주민 index 매핑
  const mbtiMap = {
    "INTJ": 0,  "ENTJ": 0,
    "ENFJ": 1,  "ESFJ": 1,
    "ENTP": 2,  "ESTP": 7,
    "ISFJ": 3,  "INFJ": 3,
    "INTP": 4,  "INFP": 8,
    "ENFP": 5,  "ESFP": 9,
    "ISFP": 6,  "ISTP": 6,
    "ESTJ": 10, "ISTJ": 10
  };

  return {
    index: mbtiMap[mbtiType] ?? 0,
    mbtiType
  };
}
